_GPS_RE = re.compile(r"(-?\d{1,2}\.\d+)\s*[,;]\s*(-?\d{1,3}\.\d+)")


def parse_gps(text):
    """Первая пара "lat, lng" в тексте -> (lat, lng) или None."""
    m = _GPS_RE.search(str(text or ""))
    if not m:
        return None
    lat, lng = float(m.group(1)), float(m.group(2))
    if -90 <= lat <= 90 and -180 <= lng <= 180:
        return lat, lng
    return None


